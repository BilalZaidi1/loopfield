// Copies the pure TypeScript rules engine into supabase/functions/_shared/core so edge functions can
// be deployed without workspace resolution. CI runs `node scripts/sync-core.mjs --check`.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync, statSync, existsSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'packages/core/src');
const dest = join(root, 'supabase/functions/_shared/core');
const check = process.argv.includes('--check');
const header = '// GENERATED by scripts/sync-core.mjs from packages/core/src — do not edit.\n';

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.ts') ? [p] : [];
  });
}

let drift = 0;
const files = walk(src);
if (!check && existsSync(dest)) rmSync(dest, { recursive: true });
for (const file of files) {
  const rel = relative(src, file);
  const out = join(dest, rel);
  const content = header + readFileSync(file, 'utf8');
  if (check) {
    if (!existsSync(out) || readFileSync(out, 'utf8') !== content) { console.error(`out of sync: ${rel}`); drift++; }
  } else {
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, content);
  }
}
if (check && drift) process.exit(1);
console.log(check ? 'core copy in sync' : `synced ${files.length} files to ${relative(root, dest)}`);
