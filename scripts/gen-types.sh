#!/usr/bin/env bash
# Regenerate apps/mobile/src/lib/database.types.ts (Supabase TypeScript types for the public schema).
#
#   scripts/gen-types.sh            build a disposable local database from supabase/migrations (scripts/test-db.sh)
#                                   and run postgres-meta's generator, the one `supabase gen types` uses. No Docker
#                                   or remote project needed.
#   scripts/gen-types.sh --remote   generate from the linked remote project with the Supabase CLI 3.x instead
#                                   (all migrations must be applied there first).
#   scripts/gen-types.sh --check    regenerate locally and fail if the committed file differs (used by CI).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/apps/mobile/src/lib/database.types.ts"
PGMETA_VERSION="0.100.0"
CACHE="${PGMETA_CACHE:-${XDG_CACHE_HOME:-$HOME/.cache}/loopfield/postgres-meta-$PGMETA_VERSION}"
HEADER=$'// GENERATED by scripts/gen-types.sh (postgres-meta typegen over supabase/migrations) — do not edit.\n// Regenerate after every migration change; CI fails when this file is stale.\n'
mode="${1:-local}"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT

if [[ "$mode" == "--remote" ]]; then
  command -v supabase >/dev/null || { echo "Supabase CLI not found (https://supabase.com/docs/guides/cli)"; exit 2; }
  supabase gen types typescript --remote --schema public > "$tmp"
else
  if [[ ! -f "$CACHE/node_modules/@supabase/postgres-meta/dist/server/server.js" ]]; then
    mkdir -p "$CACHE"
    npm install --prefix "$CACHE" --no-audit --no-fund --silent "@supabase/postgres-meta@$PGMETA_VERSION" >/dev/null
  fi
  URL="$(bash "$ROOT/scripts/test-db.sh" --migrate-only 2>/dev/null | tail -1)"
  PG_META_DB_URL="$URL" PG_META_GENERATE_TYPES=typescript PG_META_GENERATE_TYPES_INCLUDED_SCHEMAS=public \
    PG_META_GENERATE_TYPES_DETECT_ONE_TO_ONE_RELATIONSHIPS=true \
    node "$CACHE/node_modules/@supabase/postgres-meta/dist/server/server.js" > "$tmp" 2>/dev/null
fi
grep -q "export type Database" "$tmp" || { echo "type generation produced no Database type"; exit 1; }
{ printf '%s\n' "$HEADER"; cat "$tmp"; } > "$tmp.full"
if [[ "$mode" == "--check" ]]; then
  if ! diff -q "$tmp.full" "$OUT" >/dev/null; then
    rm -f "$tmp.full"
    echo "apps/mobile/src/lib/database.types.ts is stale: run scripts/gen-types.sh and commit the result"; exit 1
  fi
  rm -f "$tmp.full"; echo "database types up to date"
else
  mv "$tmp.full" "$OUT"; echo "wrote ${OUT#$ROOT/}"
fi
